-- Compatible with MySQL 5.7.44 / InnoDB / utf8mb4.
-- All business quantity constraints are validated by locked PHP transactions (MySQL 5.7 does not enforce CHECK).
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NULL UNIQUE, phone VARCHAR(40) NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(30) NOT NULL DEFAULT 'employee',
 permissions_json LONGTEXT NOT NULL, custom_json LONGTEXT NULL, active TINYINT(1) NOT NULL DEFAULT 1,
 must_change_password TINYINT(1) NOT NULL DEFAULT 1,
 last_login_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS app_settings (`key` VARCHAR(100) PRIMARY KEY, value_json LONGTEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS menu_settings(module VARCHAR(30) PRIMARY KEY, label VARCHAR(100) NOT NULL, position INT NOT NULL DEFAULT 0, visible TINYINT NOT NULL DEFAULT 1) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS field_definitions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, module VARCHAR(30) NOT NULL,
 field_key VARCHAR(80) NOT NULL, label VARCHAR(100) NOT NULL, field_type VARCHAR(30) NOT NULL DEFAULT 'text',
 builtin TINYINT(1) NOT NULL DEFAULT 0, protected TINYINT(1) NOT NULL DEFAULT 0,
 visible TINYINT(1) NOT NULL DEFAULT 1, list_visible TINYINT(1) NOT NULL DEFAULT 1,
 required_field TINYINT(1) NOT NULL DEFAULT 0, position INT NOT NULL DEFAULT 0,
 options_json LONGTEXT NULL, placeholder VARCHAR(250) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1,
 UNIQUE KEY ux_module_field(module,field_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reference_values (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, group_code VARCHAR(40) NOT NULL, value VARCHAR(150) NOT NULL,
 position INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1,
 UNIQUE KEY ux_group_value(group_code,value)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS parties (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(190) NOT NULL,
 kind VARCHAR(30) NOT NULL DEFAULT 'factory', note TEXT NULL, custom_json LONGTEXT NULL, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS warehouses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(190) NOT NULL, party_id BIGINT UNSIGNED NULL,
 location VARCHAR(190) NOT NULL DEFAULT '', custom_json LONGTEXT NULL, active TINYINT NOT NULL DEFAULT 1,
 FOREIGN KEY (party_id) REFERENCES parties(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS uploads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, stored_name VARCHAR(100) NOT NULL UNIQUE, mime VARCHAR(100) NOT NULL,
 original_name VARCHAR(190) NOT NULL, uploaded_by BIGINT UNSIGNED NULL, created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sku VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(190) NOT NULL, spec VARCHAR(190) NOT NULL DEFAULT '', color VARCHAR(100) NOT NULL DEFAULT '',
 material VARCHAR(120) NOT NULL DEFAULT '', category VARCHAR(120) NOT NULL DEFAULT '',
 unit VARCHAR(30) NOT NULL DEFAULT '件', description TEXT NULL,
 reference_price_cny DECIMAL(18,4) NOT NULL DEFAULT 0, safety_stock DECIMAL(18,3) NOT NULL DEFAULT 0,
 photo_id BIGINT UNSIGNED NULL, custom_json LONGTEXT NULL,
 active TINYINT NOT NULL DEFAULT 1, created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (photo_id) REFERENCES uploads(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_lots (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, lot_code VARCHAR(100) NOT NULL,
 owner_party_id BIGINT UNSIGNED NOT NULL, warehouse_id BIGINT UNSIGNED NOT NULL,
 grade VARCHAR(100) NOT NULL DEFAULT 'A级', location VARCHAR(100) NOT NULL DEFAULT '',
 quantity DECIMAL(18,3) NOT NULL DEFAULT 0, reserved DECIMAL(18,3) NOT NULL DEFAULT 0,
 unit_cost_cny DECIMAL(18,4) NOT NULL DEFAULT 0, photo_id BIGINT UNSIGNED NULL,
 custom_json LONGTEXT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY ux_lot_location (lot_code,product_id,owner_party_id,warehouse_id),
 FOREIGN KEY (product_id) REFERENCES products(id),
 FOREIGN KEY (owner_party_id) REFERENCES parties(id), FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
 FOREIGN KEY (photo_id) REFERENCES uploads(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customer_code VARCHAR(50) UNIQUE,
 name VARCHAR(190) NOT NULL, country VARCHAR(120) NOT NULL DEFAULT '',
 contact VARCHAR(150) NOT NULL DEFAULT '', email VARCHAR(190) NOT NULL DEFAULT '',
 phone VARCHAR(80) NOT NULL DEFAULT '', owner_user_id BIGINT UNSIGNED NULL,
 source VARCHAR(100) NOT NULL DEFAULT '', tags_json LONGTEXT NULL, custom_json LONGTEXT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS leads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, lead_code VARCHAR(50) UNIQUE,
 customer_id BIGINT UNSIGNED NOT NULL, title VARCHAR(190) NOT NULL,
 source VARCHAR(100) NOT NULL DEFAULT '', status VARCHAR(80) NOT NULL DEFAULT '新询盘',
 currency VARCHAR(10) NOT NULL DEFAULT 'USD', expected_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
 fx_to_cny DECIMAL(16,6) NOT NULL DEFAULT 1, estimated_cost_cny DECIMAL(18,2) NOT NULL DEFAULT 0,
 probability DECIMAL(5,2) NOT NULL DEFAULT 0, note TEXT NULL, custom_json LONGTEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (customer_id) REFERENCES customers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sales_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_code VARCHAR(60) NOT NULL UNIQUE,
 customer_id BIGINT UNSIGNED NOT NULL, lead_id BIGINT UNSIGNED NULL,
 order_date DATE NOT NULL, status VARCHAR(70) NOT NULL DEFAULT '待处理',
 currency VARCHAR(10) NOT NULL DEFAULT 'USD', amount DECIMAL(18,2) NOT NULL DEFAULT 0,
 fx_to_cny DECIMAL(16,6) NOT NULL DEFAULT 1, notes TEXT NULL, custom_json LONGTEXT NULL,
 created_by BIGINT UNSIGNED NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (customer_id) REFERENCES customers(id), FOREIGN KEY (lead_id) REFERENCES leads(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL, lot_id BIGINT UNSIGNED NULL,
 qty DECIMAL(18,3) NOT NULL, unit_cost_cny DECIMAL(18,4) NOT NULL DEFAULT 0,
 FOREIGN KEY (order_id) REFERENCES sales_orders(id) ON DELETE CASCADE,
 FOREIGN KEY (product_id) REFERENCES products(id), FOREIGN KEY (lot_id) REFERENCES stock_lots(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_reservations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, lot_id BIGINT UNSIGNED NOT NULL,
 order_id BIGINT UNSIGNED NOT NULL, qty DECIMAL(18,3) NOT NULL DEFAULT 0,
 UNIQUE KEY ux_reservation(lot_id,order_id),
 FOREIGN KEY (lot_id) REFERENCES stock_lots(id), FOREIGN KEY (order_id) REFERENCES sales_orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, lot_id BIGINT UNSIGNED NOT NULL,
 movement_type VARCHAR(30) NOT NULL, qty DECIMAL(18,3) NOT NULL,
 before_qty DECIMAL(18,3) NOT NULL, after_qty DECIMAL(18,3) NOT NULL,
 customer_id BIGINT UNSIGNED NULL, order_id BIGINT UNSIGNED NULL,
 remark VARCHAR(500) NOT NULL DEFAULT '', created_by BIGINT UNSIGNED NOT NULL, custom_json LONGTEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (lot_id) REFERENCES stock_lots(id), FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL,
 FOREIGN KEY (order_id) REFERENCES sales_orders(id) ON DELETE SET NULL,
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cost_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NULL,
 cost_date DATE NOT NULL, category VARCHAR(100) NOT NULL,
 amount_cny DECIMAL(18,2) NOT NULL, note VARCHAR(500) NOT NULL DEFAULT '', custom_json LONGTEXT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES sales_orders(id) ON DELETE CASCADE,
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS receipts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 receipt_date DATE NOT NULL, amount DECIMAL(18,2) NOT NULL,
 currency VARCHAR(10) NOT NULL DEFAULT 'USD', fx_to_cny DECIMAL(16,6) NOT NULL DEFAULT 1,
 amount_cny DECIMAL(18,2) NOT NULL, note VARCHAR(500) NOT NULL DEFAULT '', created_by BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (order_id) REFERENCES sales_orders(id) ON DELETE CASCADE,
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS quotes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, quote_code VARCHAR(60) NOT NULL UNIQUE,
 product_id BIGINT UNSIGNED NULL, lot_id BIGINT UNSIGNED NULL, customer_id BIGINT UNSIGNED NULL,
 currency VARCHAR(10) NOT NULL DEFAULT 'USD', fx_to_cny DECIMAL(16,6) NOT NULL,
 term VARCHAR(10) NOT NULL, qty DECIMAL(18,3) NOT NULL, unit VARCHAR(30) NOT NULL,
 unit_cost_cny DECIMAL(18,4) NOT NULL,
 margin_pct DECIMAL(6,3) NOT NULL DEFAULT 0, commission_pct DECIMAL(6,3) NOT NULL DEFAULT 0,
 fees_json LONGTEXT NOT NULL, custom_json LONGTEXT NULL, quote_total DECIMAL(18,2) NOT NULL, expected_profit_cny DECIMAL(18,2) NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL,
 FOREIGN KEY (lot_id) REFERENCES stock_lots(id) ON DELETE SET NULL,
 FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
 action VARCHAR(80) NOT NULL, entity VARCHAR(80) NOT NULL, entity_id VARCHAR(80) NULL,
 payload_json LONGTEXT NULL, ip VARCHAR(45) NOT NULL DEFAULT '', created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
 INDEX ix_audit_time(created_at), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, address_hash CHAR(64) NOT NULL,
 attempted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX ix_attempts(address_hash,attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
